package club.ttg.subscriber.domain.subscription.model;

/**
 * Что произошло с подпиской пользователя — запись истории для админки.
 */
public enum SubscriptionEventType {
    /** Пользователь оплатил месяцы подписки. */
    PURCHASE,
    /** Администратор выдал или продлил подписку бесплатно. */
    GRANT,
    /** Администратор досрочно отключил подписку. */
    REVOKE,
    /** Пользователь погасил промокод с подпиской (срок ещё не идёт). */
    CODE_REDEEM,
    /** Пользователь активировал подписку из промокода — срок пошёл. */
    ACTIVATE
}
