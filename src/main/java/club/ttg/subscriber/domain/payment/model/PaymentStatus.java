package club.ttg.subscriber.domain.payment.model;

/**
 * Состояние платежа за подписку.
 */
public enum PaymentStatus {
    /** Платёж создан, пользователь отправлен на форму оплаты. */
    CREATED,
    /** Платёжный сервис подтвердил оплату, подписка продлена. */
    PAID,
    /** Уведомление отклонено (сумма, валюта или режим не сходятся), подписка не выдана. */
    REJECTED
}
